def o(label, next=None, ask=None, exclusive=False, rec=True, say=None):
    return {"label": label, "next": next, "ask": ask,
            "exclusive": exclusive, "rec": rec, "say": say}


def nav(label, target):
    """Кнопка-переход, в заявку не записывается."""
    return o(label, next=target, rec=False)


def step(sid, group, title, text, type="single", options=(), next=None, record=True, **kw):
    STEPS[sid] = {"id": sid, "group": group, "title": title, "text": text, "type": type,
                  "options": list(options), "next": next, "record": record, **kw}
    GROUPS[group].append(sid)


